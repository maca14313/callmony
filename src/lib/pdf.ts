import { jsPDF } from "jspdf";
import type { CalcList, Contact, LedgerEntry } from "./types";
import { lineTotal, listTotals, entryRemaining, entrySignedRemaining, ownerBalance } from "./calc";
import { displayName, money } from "./utils";

/* Client-side PDF generation — works fully offline. */

const BRAND: [number, number, number] = [22, 160, 133];
const INK: [number, number, number] = [23, 43, 42];
const MUTE: [number, number, number] = [120, 135, 131];
const NEG: [number, number, number] = [214, 96, 100];

function header(doc: jsPDF, title: string, subtitle?: string) {
  doc.setFillColor(...BRAND);
  doc.roundedRect(14, 14, 42, 42, 10, 10, "F");
  doc.setTextColor(255, 255, 255);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(20);
  doc.text("d.", 24, 41);
  doc.setTextColor(...INK);
  doc.setFontSize(17);
  doc.text(title, 64, 26);
  if (subtitle) {
    doc.setFont("helvetica", "normal");
    doc.setFontSize(10);
    doc.setTextColor(...MUTE);
    doc.text(subtitle, 64, 35);
  }
  doc.setDrawColor(232, 239, 236);
  doc.setLineWidth(0.8);
  doc.line(14, 62, 196, 62);
}

function footer(doc: jsPDF) {
  doc.setFont("helvetica", "normal");
  doc.setFontSize(8);
  doc.setTextColor(...MUTE);
  doc.text(
    `Generated by dial. · ${new Date().toLocaleString()} · offline-first`,
    105,
    288,
    { align: "center" }
  );
}

/** PDF for a calculating list — bill with rows, totals. */
export function listToPdfBlob(list: CalcList, contact?: Contact | null, currency = "ETB"): Blob {
  const doc = new jsPDF({ unit: "mm", format: "a5" });
  const pageW = doc.internal.pageSize.getWidth();
  const pageH = doc.internal.pageSize.getHeight();
  const t = listTotals(list);
  const cur = list.currency || currency;

  header(
    doc,
    list.title.slice(0, 30),
    `${contact ? `${displayName(contact)} · ` : ""}${new Date().toLocaleDateString()}`
  );

  let y = 72;
  doc.setFontSize(9);
  doc.setTextColor(...MUTE);
  doc.text("ITEM", 14, y);
  doc.text("QTY", 118, y, { align: "right" });
  doc.text("PRICE", 146, y, { align: "right" });
  doc.text("TOTAL", pageW - 14, y, { align: "right" });
  y += 4;
  doc.setDrawColor(240, 245, 243);
  doc.line(14, y, pageW - 14, y);
  y += 7;

  doc.setTextColor(...INK);
  doc.setFontSize(10);
  list.items.slice(0, 22).forEach((i) => {
    if (y > pageH - 70) {
      doc.addPage();
      y = 20;
    }
    const lt = lineTotal(i);
    doc.text(String(i.name || "—").slice(0, 34), 14, y);
    doc.text(`${i.qty}${i.unit ? ` ${i.unit}` : ""}`, 118, y, { align: "right" });
    doc.text(money(i.unitPrice, cur), 146, y, { align: "right" });
    doc.text(money(lt, cur), pageW - 14, y, { align: "right" });
    y += 6.5;
  });
  if (list.items.length > 22) {
    doc.setTextColor(...MUTE);
    doc.text(`… and ${list.items.length - 22} more items`, 14, y);
    y += 6.5;
  }

  y += 3;
  doc.setDrawColor(232, 239, 236);
  doc.line(110, y, pageW - 14, y);
  y += 7;

  const row = (label: string, value: string, bold = false, color = INK) => {
    doc.setFont("helvetica", bold ? "bold" : "normal");
    doc.setTextColor(...color);
    doc.text(label, pageW - 66, y);
    doc.text(value, pageW - 14, y, { align: "right" });
    y += 6.5;
  };
  if (t.listDiscount > 0) row("Discount", `− ${money(t.listDiscount, cur)}`);
  if (t.listTax > 0) row("Tax", `+ ${money(t.listTax, cur)}`);
  if (t.extra > 0) row("Extra", `+ ${money(t.extra, cur)}`);
  row("Total", money(t.grand, cur), true);
  row("Paid", money(t.paid, cur), false, BRAND);
  row("Pending", money(t.pending, cur), true, t.pending > 0 ? NEG : BRAND);

  if (list.note) {
    y += 4;
    doc.setFont("helvetica", "normal");
    doc.setFontSize(9);
    doc.setTextColor(...MUTE);
    doc.text(`Note: ${list.note.slice(0, 80)}`, 14, y);
  }
  footer(doc);
  return doc.output("blob");
}

/** Statement PDF for a contact (or General) — entries with running balance. */
export function statementToPdfBlob(
  entries: LedgerEntry[],
  owner: Contact | null,
  currency = "ETB"
): Blob {
  const doc = new jsPDF({ unit: "mm", format: "a4" });
  const pageW = doc.internal.pageSize.getWidth();
  const pageH = doc.internal.pageSize.getHeight();
  const live = entries.filter((e) => !e.deletedAt).sort((a, b) => a.date.localeCompare(b.date));
  const balance = ownerBalance(entries, owner?.id || "general");

  header(
    doc,
    "Statement",
    `${owner ? displayName(owner) : "General"} · ${live.length} entries · ${new Date().toLocaleDateString()}`
  );

  let y = 74;
  let running = 0;
  doc.setFontSize(9);
  doc.setTextColor(...MUTE);
  doc.text("DATE", 14, y);
  doc.text("DESCRIPTION", 40, y);
  doc.text("AMOUNT", 128, y, { align: "right" });
  doc.text("BALANCE", pageW - 14, y, { align: "right" });
  y += 5;
  doc.setDrawColor(240, 245, 243);
  doc.line(14, y, pageW - 14, y);
  y += 7;

  doc.setFontSize(10);
  live.forEach((e) => {
    if (y > pageH - 30) {
      doc.addPage();
      y = 20;
    }
    const signed = entrySignedRemaining(e);
    running += signed;
    doc.setTextColor(...INK);
    doc.text(e.date, 14, y);
    const desc = `${e.type === "credit" ? (owner ? "Credit" : "Income") : owner ? "Debit" : "Expense"}${e.category ? ` · ${e.category}` : ""}${e.note ? ` · ${e.note.slice(0, 26)}` : ""}`;
    doc.text(desc.slice(0, 48), 40, y);
    const amt = `${signed >= 0 ? "+" : "−"}${money(Math.abs(signed), currency)}`;
    doc.setTextColor(...(signed >= 0 ? BRAND : NEG));
    doc.text(amt, 128, y, { align: "right" });
    doc.setTextColor(...INK);
    doc.text(money(running, currency), pageW - 14, y, { align: "right" });
    y += 6.5;
  });

  y += 4;
  doc.setFillColor(234, 247, 242);
  doc.roundedRect(14, y, pageW - 28, 16, 4, 4, "F");
  doc.setFont("helvetica", "bold");
  doc.setFontSize(11);
  doc.setTextColor(...(balance >= 0 ? BRAND : NEG));
  const label = !owner
    ? `Net: ${money(balance, currency)}`
    : balance > 0
      ? `They owe you ${money(balance, currency)}`
      : balance < 0
        ? `You owe them ${money(Math.abs(balance), currency)}`
        : "Settled up ✓";
  doc.text(label, pageW / 2, y + 10.5, { align: "center" });
  footer(doc);
  return doc.output("blob");
}

/** Payment-receipt style text for WhatsApp / SMS sharing. */
export function listShareText(list: CalcList, contact?: Contact | null, currency = "ETB"): string {
  const t = listTotals(list);
  const cur = list.currency || currency;
  const lines: string[] = [];
  lines.push(`*${list.title}*`);
  if (contact) lines.push(`For: ${displayName(contact)}`);
  lines.push("");
  list.items.forEach((i) => {
    const lt = lineTotal(i);
    lines.push(`• ${i.name} ×${i.qty}${i.unit ? ` ${i.unit}` : ""} — ${money(lt, cur)}`);
  });
  if (t.listDiscount > 0) lines.push(`Discount: −${money(t.listDiscount, cur)}`);
  if (t.listTax > 0) lines.push(`Tax: +${money(t.listTax, cur)}`);
  if (t.extra > 0) lines.push(`Extra: +${money(t.extra, cur)}`);
  lines.push("");
  lines.push(`*Total: ${money(t.grand, cur)}*`);
  if (t.paid > 0) lines.push(`Paid: ${money(t.paid, cur)}`);
  lines.push(`*Pending: ${money(t.pending, cur)}*`);
  lines.push("");
  lines.push("Sent from dial. 📞");
  return lines.join("\n");
}

export function statementShareText(
  entries: LedgerEntry[],
  owner: Contact | null,
  currency = "ETB"
): string {
  const live = entries.filter((e) => !e.deletedAt);
  const balance = ownerBalance(live, owner?.id || "general");
  const lines = [
    `*Statement — ${owner ? displayName(owner) : "General"}*`,
    `${live.length} entries`,
    "",
  ];
  live
    .sort((a, b) => a.date.localeCompare(b.date))
    .slice(-8)
    .forEach((e) => {
      const rem = entryRemaining(e);
      lines.push(`• ${e.date} ${e.type === "credit" ? "Credit" : "Debit"} ${money(e.amount, currency)} (paid ${money(e.amount - rem, currency)})`);
    });
  lines.push("");
  if (owner) {
    lines.push(
      balance > 0
        ? `*They owe you ${money(balance, currency)}*`
        : balance < 0
          ? `*You owe them ${money(Math.abs(balance), currency)}*`
          : "*Settled up ✓*"
    );
  } else {
    lines.push(`*Net: ${money(balance, currency)}*`);
  }
  lines.push("", "Sent from dial. 📞");
  return lines.join("\n");
}
